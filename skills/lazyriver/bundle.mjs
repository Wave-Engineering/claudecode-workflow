#!/usr/bin/env node
// bundle.mjs — deterministic single-file Workflow bundler for /lazyriver (#844).
//
// WHY THIS EXISTS (same reason as the wave engine's bundler): a Dynamic Workflow MUST be ONE
// self-contained file with `export const meta` as the literal first statement — cross-file
// `import`s do NOT run as a Workflow. But the pure, deterministic halves (the schemas, the prompt
// builders, and `cordCheck`) live in a separate module (river.js) SO THEY CAN BE UNIT-TESTED (a
// Workflow file can't be imported by a node test — it uses top-level `return`/`await`, illegal in
// a plain ESM module). This bundler reconciles the two: river.js + lazyriver-workflow.js stay the
// tested, reviewed source-of-truth; this script inlines them into the single-file artifact
// `lazyriver-workflow.bundled.js` that the Workflow tool actually invokes. A regression test
// (tests/regression/test_lazyriver_bundle_in_sync.sh) asserts the committed bundle matches a fresh
// regeneration, so the two never drift.
//
// USAGE:
//   node skills/lazyriver/bundle.mjs            # regenerate the committed bundle
//   node skills/lazyriver/bundle.mjs --check    # exit 1 if the committed bundle is stale
//
// HOW: concatenate, in dependency order, river.js → the workflow source (lazyriver-workflow.js),
// stripping every `import` statement and the `export ` keyword from helper declarations, and
// HOISTING `export const meta = {…}` (kept exported — the runtime needs it) to the very top so it
// is the first statement. Function declarations hoist; the module arrow-const helpers are emitted
// before the workflow body that calls them, so init order holds. NOTE: meta's string values must
// not contain raw unbalanced `{`/`}` (the meta extractor brace-counts) — the --check test + a
// `node --check` of the output catch any breakage.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const DIR = dirname(fileURLToPath(import.meta.url))
const MODULES = ['river.js'] // pure helpers (schemas + prompt builders + cordCheck), standalone
const MAIN = 'lazyriver-workflow.js'
const OUT = 'lazyriver-workflow.bundled.js'

// Strip ESM `import … from '…'` statements (single- AND multi-line).
function stripImports(src) {
  return src.replace(/^import\s+[\s\S]*?from\s*['"][^'"]+['"];?[ \t]*$/gm, '')
}

// Strip the `export ` keyword from helper declarations (NOT from the hoisted meta — that keeps it).
function stripExports(src) {
  return src.replace(/^export\s+(?=(async\s+function|function|const|let|var|class)\b)/gm, '')
}

// Extract `export const meta = { … }` (balanced braces) from the workflow source; return
// { metaBlock, rest } with metaBlock kept verbatim (export intact) and removed from rest.
function extractMeta(src) {
  const m = src.match(/export\s+const\s+meta\s*=\s*\{/)
  if (!m) throw new Error(`bundle: \`export const meta = {\` not found in ${MAIN}`)
  const start = m.index
  const braceOpen = src.indexOf('{', start)
  let depth = 0
  let i = braceOpen
  for (; i < src.length; i++) {
    if (src[i] === '{') depth++
    else if (src[i] === '}') {
      depth--
      if (depth === 0) {
        i++
        break
      }
    }
  }
  if (depth !== 0) throw new Error(`bundle: unbalanced braces in \`meta\` block of ${MAIN}`)
  if (src[i] === ';') i++ // swallow an optional trailing semicolon
  return { metaBlock: src.slice(start, i), rest: src.slice(0, start) + src.slice(i) }
}

export function buildBundle() {
  const read = (f) => readFileSync(join(DIR, f), 'utf8')

  const main = read(MAIN)
  const { metaBlock, rest } = extractMeta(main)

  const modulesInlined = MODULES.map((f) => {
    const body = stripExports(stripImports(read(f))).trim()
    return `// ════════════ inlined: ${f} ════════════\n${body}\n`
  }).join('\n')

  const mainInlined = stripExports(stripImports(rest)).trim()

  return [
    `// lazyriver-workflow.bundled.js — GENERATED by skills/lazyriver/bundle.mjs. DO NOT EDIT.`,
    `// Source of truth (edit these, then re-run the bundler): ${MAIN} + ${MODULES.join(' + ')}.`,
    `// Single-file Workflow artifact: \`export const meta\` first, no imports.`,
    `// Regenerate: node skills/lazyriver/bundle.mjs   ·   Drift guard: tests/regression/test_lazyriver_bundle_in_sync.sh`,
    ``,
    metaBlock,
    ``,
    modulesInlined,
    `// ════════════ workflow body: ${MAIN} ════════════`,
    mainInlined,
    ``,
  ].join('\n')
}

// CLI: regenerate, or --check for staleness.
const isCheck = process.argv.includes('--check')
const outPath = join(DIR, OUT)
const next = buildBundle()
if (isCheck) {
  let current = ''
  try {
    current = readFileSync(outPath, 'utf8')
  } catch {
    /* missing → stale */
  }
  if (current !== next) {
    console.error(`[bundle --check] ${OUT} is STALE — run: node skills/lazyriver/bundle.mjs`)
    process.exit(1)
  }
  console.log(`[bundle --check] ${OUT} is up to date`)
} else {
  writeFileSync(outPath, next)
  console.log(`[bundle] wrote ${OUT} (${next.length} bytes)`)
}
