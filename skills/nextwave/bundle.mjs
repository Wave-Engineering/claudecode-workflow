#!/usr/bin/env node
// bundle.mjs — deterministic single-file Workflow bundler for the per-wave engine (#699/#2).
//
// WHY THIS EXISTS (live-gate finding #2): a Dynamic Workflow MUST be ONE self-contained file
// with `export const meta` as the literal first statement — cross-file `import`s do NOT run as a
// Workflow. But the engine's pure, deterministic halves (parseRehydrate / toBlob / the gate
// prompt builders + conservativeFail) live in separate modules SO THEY CAN BE UNIT-TESTED
// (a Workflow file can't be imported by a node test — it uses top-level `return`/`await`, illegal
// in a plain ESM module). This bundler reconciles the two: the modules + the workflow source stay
// the tested, reviewed source-of-truth; this script inlines them into the single-file artifact
// `per-wave-workflow.bundled.js` that the Workflow tool actually invokes. A regression test
// (tests/regression/test_bundle_in_sync.sh) asserts the committed bundle matches a fresh
// regeneration, so the two never drift.
//
// USAGE:
//   node skills/nextwave/bundle.mjs            # regenerate the committed bundle
//   node skills/nextwave/bundle.mjs --check    # exit 1 if the committed bundle is stale
//
// HOW: concatenate, in dependency order, wave-status.js → resume.js → gate.js → the workflow
// source (per-wave-workflow.js), stripping every `import` statement and the `export ` keyword from
// helper declarations, and HOISTING `export const meta = {…}` (kept exported — the runtime needs it)
// to the very top so it is the first statement. Function declarations hoist; the module arrow-const
// helpers (wtRoot/blobPath/…) are emitted before the workflow body that calls them, so init order
// holds. NOTE: meta's string values must not contain raw unbalanced `{`/`}` (the meta extractor
// brace-counts) — the --check test + a `node --check` of the output catch any breakage.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const DIR = dirname(fileURLToPath(import.meta.url))
const MODULES = ['wave-status.js', 'resume.js', 'gate.js'] // dependency order: resume imports from wave-status
const MAIN = 'per-wave-workflow.js'
const OUT = 'per-wave-workflow.bundled.js'

// Strip ESM `import … from '…'` statements (single- AND multi-line). The lazy body stops at the
// first `from '…'` that ends a line, so each import block is removed independently.
function stripImports(src) {
  return src.replace(/^import\s+[\s\S]*?from\s*['"][^'"]+['"];?[ \t]*$/gm, '')
}

// Strip the `export ` keyword from helper declarations (NOT from the hoisted meta — that keeps it).
// Only at statement start, before a declaration keyword, so it never touches the word "export" in
// a string or comment.
function stripExports(src) {
  return src.replace(/^export\s+(?=(async\s+function|function|const|let|var|class)\b)/gm, '')
}

// Extract `export const meta = { … }` (balanced braces) from the workflow source; return
// { metaBlock, rest } with metaBlock kept verbatim (export intact) and removed from rest.
function extractMeta(src) {
  const m = src.match(/export\s+const\s+meta\s*=\s*\{/)
  if (!m) throw new Error(`bundle: \`export const meta = {\` not found in ${MAIN}`)
  const start = m.index
  const braceOpen = src.indexOf('{', start)
  let depth = 0
  let i = braceOpen
  for (; i < src.length; i++) {
    if (src[i] === '{') depth++
    else if (src[i] === '}') {
      depth--
      if (depth === 0) {
        i++
        break
      }
    }
  }
  if (depth !== 0) throw new Error(`bundle: unbalanced braces in \`meta\` block of ${MAIN}`)
  if (src[i] === ';') i++ // swallow an optional trailing semicolon
  return { metaBlock: src.slice(start, i), rest: src.slice(0, start) + src.slice(i) }
}

export function buildBundle() {
  const read = (f) => readFileSync(join(DIR, f), 'utf8')

  const main = read(MAIN)
  const { metaBlock, rest } = extractMeta(main)

  const modulesInlined = MODULES.map((f) => {
    const body = stripExports(stripImports(read(f))).trim()
    return `// ════════════ inlined: ${f} ════════════\n${body}\n`
  }).join('\n')

  const mainInlined = stripExports(stripImports(rest)).trim()

  return [
    `// per-wave-workflow.bundled.js — GENERATED by skills/nextwave/bundle.mjs. DO NOT EDIT.`,
    `// Source of truth (edit these, then re-run the bundler): ${MAIN} + ${MODULES.join(' + ')}.`,
    `// Single-file Workflow artifact (live-gate finding #2): \`export const meta\` first, no imports.`,
    `// Regenerate: node skills/nextwave/bundle.mjs   ·   Drift guard: tests/regression/test_bundle_in_sync.sh`,
    ``,
    metaBlock,
    ``,
    modulesInlined,
    `// ════════════ workflow body: ${MAIN} ════════════`,
    mainInlined,
    ``,
  ].join('\n')
}

// CLI: regenerate, or --check for staleness.
const isCheck = process.argv.includes('--check')
const outPath = join(DIR, OUT)
const next = buildBundle()
if (isCheck) {
  let current = ''
  try {
    current = readFileSync(outPath, 'utf8')
  } catch {
    /* missing → stale */
  }
  if (current !== next) {
    console.error(`[bundle --check] ${OUT} is STALE — run: node skills/nextwave/bundle.mjs`)
    process.exit(1)
  }
  console.log(`[bundle --check] ${OUT} is up to date`)
} else {
  writeFileSync(outPath, next)
  console.log(`[bundle] wrote ${OUT} (${next.length} bytes)`)
}
